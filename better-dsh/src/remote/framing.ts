/**
 * Framing stack for the remote tool — pure module, zero imports (plan
 * docs/10_plans/2026-09-22-dashr-remote-tool-rm0.md, Task 3; design §4.2).
 *
 * Everything here runs against one byte stream, in two modes:
 *
 * - **PTY 主路径（OSC 133 framing）**: {@link buildEngineRc} generates the
 *   rcfile that makes bash emit an OSC 133 `C` marker once a command line is
 *   read (`PS0`) and an OSC 133 `D;<exit>` marker plus a *separate standard
 *   OSC 7* cwd report at every prompt (`PROMPT_COMMAND`); markers terminate
 *   with BEL (`\x07`) or ST (`\x1b\\`). {@link createFrameParser} reassembles
 *   those markers across arbitrary chunk boundaries (a split inside a marker
 *   loses no bytes), strips the consumed sequences, emits {@link Frame}s and
 *   exposes the raw output between `C` and `D` via `takePendingOutput()`
 *   (feed through {@link stripAnsi} before handing it to the model). A `D`
 *   frame waits for its OSC 7 so `cwd` attaches even when it lands in a later
 *   chunk; a `D` without a preceding `C` (the first prompt of a fresh
 *   session) is a real frame but leaves no dangling output.
 * - **exec 退化路径（哨兵）**: {@link buildDegradedCommand} wraps a command
 *   with a cwd guard (`CWD_GONE` sentinel, exit 127) and a tail sentinel
 *   carrying `$?` and `$PWD`; {@link parseDegradedOutput} reads them back.
 *
 * @module dashr/remote/framing
 */

/** bash 每次读到命令行（PS0）发 C；每个 prompt（PROMPT_COMMAND）发 D;<exit> 和标准 OSC 7 cwd。 */
export function buildEngineRc(): string {
  return [
    '# dashr engine rcfile — generated by dashr/remote/framing, do not edit.',
    'for f in ~/.profile ~/.bash_profile ~/.bashrc; do [ -f "$f" ] && . "$f"; done',
    'stty -echo 2>/dev/null || true',
    `PS1=''`,
    `PS0=$'\\033]133;C\\007'`,
    `PROMPT_COMMAND='printf "\\033]133;D;%s\\007" "$?" ; printf "\\033]7;file://%s\\007" "$PWD"'`,
    'export TERM=dumb',
    '',
  ].join('\n')
}

export type Frame =
  | { kind: 'command-start' }
  | { kind: 'command-end'; exitCode: number; cwd?: string } // cwd 来自随后（或同行）的 OSC 7

export interface FrameParser {
  /** 跨 chunk 累积；剥掉已消费的 OSC 序列 */
  push(chunk: string): Frame[]
  /** 两个标记之间的原始输出（喂 stripAnsi 后给模型） */
  takePendingOutput(): string
}

// 完整标记（三选一，互斥）：C / D;<exit> / 7;file://<path>，BEL 或 ST 终止。
// OSC 7 的 path 部分（[^\x07\x1b]*）与 D 的数字部分都排除内嵌 ESC，故标记不会重叠。
const MARKER = /\x1b\](?:(133;C)|(133;D;(\d+))|(7;file:\/\/([^\x07\x1b]*)))(?:\x07|\x1b\\)/g

const C_BODY = '133;C'
const D_BODY_PREFIX = /^133;D;?\d*$/
const D_BODY_COMPLETE = /^133;D;\d+$/
// '7;file://' 字面（任意字符级前缀皆合法）+ 字面完成后的任意无 BEL/ESC 字符。
// 程序化前缀判断而非手写嵌套正则——嵌套版在 '\x1b]7' 与 ';' 之间被 chunk 切开时
// 误判非前缀，marker 头被当文本放走（fuzz 实证）。
const OSC7_BODY = '7;file://'

function isSevenBodyPrefix(body: string): boolean {
  if (body.length <= OSC7_BODY.length) return OSC7_BODY.startsWith(body)
  if (!body.startsWith(OSC7_BODY)) return false
  // 字面完成后的自由段不得含 BEL/ESC：BEL 之前扫描已消费完整标记，ESC 只能是
  // 半截 ST（由调用方 partialSt 分支剥离）——否则病态残余会永久滞留 carry
  return !/[\x07\x1b]/.test(body.slice(OSC7_BODY.length))
}

/**
 * tail 的最长后缀是否可能是某个未完成标记的开头；是则返回该后缀长度（须滞留
 * carry 等下一个 chunk），否则 0。标记 body 一律不含 ESC，故候选只能起于 tail
 * 中最后一个 '\x1b]'——更早的 '\x1b]' 起的候选必把后一个 '\x1b]' 当体内 ESC，
 * 不可能是任何标记的前缀。关键：半截 ST（body 已完整、只来了 \x1b 等 \）必须
 * 与其 body 作为一个整体滞留——只扣住末尾孤 ESC 会把 body 当文本放走，标记永
 * 不闭合（D 帧丢失、OSC 7 无处可挂、原始字节漏进模型可见输出，评审实证）。
 * 宁可多滞留（下个 chunk 一到即重扫放行），绝不提前放走半截标记（那才是丢字节）。
 */
function trailingPartialMarker(tail: string): number {
  let hold = 0
  const open = tail.lastIndexOf('\x1b]')
  if (open !== -1) {
    const candidate = tail.slice(open)
    if (isMarkerPrefix(candidate)) hold = candidate.length
  }
  if (hold === 0 && tail.endsWith('\x1b')) hold = 1 // 裸 ESC（半截序列头）兜底
  return hold
}

/** candidate 是某个完整标记的真前缀（含“body 已完整、终止符只来了一半”的形态）。 */
function isMarkerPrefix(candidate: string): boolean {
  if (!candidate.startsWith('\x1b]')) return false // 裸 ESC 兜底已由调用方处理
  const rest = candidate.slice(2)
  const partialSt = rest.endsWith('\x1b') // 可能是 ST 终止符的前半（\x1b，等 \）
  const body = partialSt ? rest.slice(0, -1) : rest
  const bodyPrefix =
    C_BODY.startsWith(body) || D_BODY_PREFIX.test(body) || isSevenBodyPrefix(body)
  if (!bodyPrefix) return false
  if (!partialSt) return true // 纯 body 前缀，等余下字节
  // 带半截 ST 的：body 必须已完整，终止符才可能在途
  return body === C_BODY || D_BODY_COMPLETE.test(body) || isSevenBodyPrefix(body)
}

class FrameParserImpl implements FrameParser {
  private carry = ''          // 跨 chunk 滞留的半截标记
  private pending = ''        // 未取走的 C..D 段原始输出（已剥已消费标记）
  private inCommand = false
  private heldEnd: { exitCode: number } | undefined   // 已收 D、在等 OSC 7 挂 cwd

  push(chunk: string): Frame[] {
    this.carry += chunk
    const frames: Frame[] = []
    MARKER.lastIndex = 0
    let cursor = 0
    for (let m = MARKER.exec(this.carry); m !== null; m = MARKER.exec(this.carry)) {
      this.routeText(this.carry.slice(cursor, m.index))
      if (m[1] !== undefined) this.onCommandStart(frames)
      else if (m[2] !== undefined) this.onCommandEnd(Number(m[3]!), frames)
      else this.attachCwd(m[5] ?? '', frames)
      cursor = MARKER.lastIndex
    }
    const tail = this.carry.slice(cursor)
    const hold = trailingPartialMarker(tail)
    this.routeText(hold === 0 ? tail : tail.slice(0, tail.length - hold))
    this.carry = hold === 0 ? '' : tail.slice(tail.length - hold)
    return frames
  }

  /**
   * 两个标记之间的原始输出（喂 stripAnsi 后给模型）。取走即清空；按命令排干是
   * 调用方职责（收到 command-end 后取一次）——未排干时跨命令合并，绝不静默丢弃。
   */
  takePendingOutput(): string {
    const out = this.pending
    this.pending = ''
    return out
  }

  /** C..D 之外的文本（motd、prompt 噪音、D 后杂散）不属于任何命令段，丢弃。 */
  private routeText(text: string): void {
    if (text !== '' && this.inCommand) this.pending += text
  }

  private onCommandStart(frames: Frame[]): void {
    this.flushHeldEnd(frames) // 上一个 D 的 OSC 7 始终未到 → 无 cwd 放行
    this.inCommand = true
    frames.push({ kind: 'command-start' })
  }

  private onCommandEnd(exitCode: number, frames: Frame[]): void {
    this.inCommand = false
    this.flushHeldEnd(frames) // 病态的连续 D：先放行前者
    this.heldEnd = { exitCode } // 悬置等 OSC 7（同 chunk 或后续 chunk 均可）
  }

  private attachCwd(cwd: string, frames: Frame[]): void {
    if (this.heldEnd === undefined) return // 不跟在 D 后的 OSC 7 无处可挂
    frames.push({ kind: 'command-end', exitCode: this.heldEnd.exitCode, cwd })
    this.heldEnd = undefined
  }

  private flushHeldEnd(frames: Frame[]): void {
    if (this.heldEnd !== undefined) {
      frames.push({ kind: 'command-end', exitCode: this.heldEnd.exitCode })
      this.heldEnd = undefined
    }
  }
}

export function createFrameParser(): FrameParser {
  return new FrameParserImpl()
}

/** 剥残余 CSI/OSC（不含已被 parser 消费的标记）与其余两字节 ESC 序列。 */
export function stripAnsi(text: string): string {
  return text
    .replace(/\x1b\][^\x07\x1b]*(?:\x07|\x1b\\)/g, '') // OSC … BEL/ST
    .replace(/\x1b\[[0-9:;<=>?]*[ -/]*[@-~]/g, '')     // CSI
    .replace(/\x1b[@-Z\\-_]/g, '')                     // 其余单字符 ESC 序列
}

/** 单引号包裹 + '\'' 转义（POSIX 安全）。 */
export function shellQuote(s: string): string {
  return `'${s.replaceAll("'", `'\\''`)}'`
}

// cd 失败 → CWD_GONE 哨兵 + exit 127（第二行不再执行）；成功 → bash -lc 跑命令，
// 尾哨兵带回 rc 与 $PWD。
export function buildDegradedCommand(cmd: string, cwd: string): string {
  return [
    `cd ${shellQuote(cwd)} >/dev/null 2>&1 || { printf '\\x1eCWD_GONE\\x1e'; exit 127; }`,
    `bash -lc ${shellQuote(cmd)}; rc=$?; printf '\\x1e%d\\x1e%s\\x1e' "$rc" "$PWD"`,
  ].join('\n')
}

export interface DegradedOutcome { exitCode: number; cwd: string; output: string; cwdGone?: boolean }

const TAIL_SENTINEL = /\x1e(\d+)\x1e([^\x1e]*)\x1e$/

/** 从尾部哨兵解析；CWD_GONE → cwdGone: true（exit 127，cd 从未成功故 cwd 空）。 */
export function parseDegradedOutput(raw: string): DegradedOutcome {
  const gone = /\x1eCWD_GONE\x1e$/.exec(raw)
  if (gone !== null) {
    return { exitCode: 127, cwd: '', output: raw.slice(0, gone.index), cwdGone: true }
  }
  const m = TAIL_SENTINEL.exec(raw)
  if (m === null) {
    // 哨兵缺失（通道被杀/截断）：exitCode 未知（-1），原文整体作为 output 诚实上交
    return { exitCode: -1, cwd: '', output: raw }
  }
  return { exitCode: Number(m[1]!), cwd: m[2]!, output: raw.slice(0, m.index) }
}

/** 超帽输出保留尾窗；truncatedFrom = 截断时的原长（未截断为 undefined）。 */
export function capTail(text: string, maxChars: number): { text: string; truncatedFrom: number | undefined } {
  if (text.length <= maxChars) return { text, truncatedFrom: undefined }
  return { text: maxChars > 0 ? text.slice(-maxChars) : '', truncatedFrom: text.length }
}
