// Icon-asset generator: assets/icons/manifest.json + the referenced asset
// files → src/client/icon-assets.gen.ts (base64 data URIs the client half
// inlines). Run: node scripts/build-icon-assets.mjs (build-client runs it
// first). Only manifest-mapped assets are inlined — the unmapped remainder of
// the pack stays a source-tree collection, never bundle weight.
// Regenerate whenever assets/ or manifest.json change; the output is committed
// and byte-deterministic (sorted keys, fixed template, no timestamps).
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const ASSETS = join(root, 'assets', 'icons')
const OUT = join(root, 'src', 'client', 'icon-assets.gen.ts')

const manifest = JSON.parse(readFileSync(join(ASSETS, 'manifest.json'), 'utf8'))
if (manifest.version !== 1) throw new Error(`icon-assets: unsupported manifest version ${manifest.version}`)
/** runtimeId → file, e.g. `agent-omp → omp.svg`; the UI's only icon lookup. */
const map = manifest.map
if (typeof map !== 'object' || map === null || Array.isArray(map)) throw new Error('icon-assets: manifest.map must be an object')
const tiles = typeof manifest.tiles === 'object' && manifest.tiles !== null ? manifest.tiles : {}

const MIME = { '.svg': 'image/svg+xml', '.png': 'image/png' }

/** Intrinsic width/height: SVG root attributes, PNG IHDR bytes. */
function dimensions(file, bytes) {
  if (file.endsWith('.svg')) {
    const text = bytes.toString('utf8')
    const viewBox = /viewBox="([^"]+)"/.exec(text)?.[1]?.trim().split(/\s+/).map(Number)
    if (viewBox !== undefined && viewBox.length === 4 && viewBox.every((n) => Number.isFinite(n) && n > 0)) {
      return { width: viewBox[2], height: viewBox[3] }
    }
    const width = Number(/width="([\d.]+)"/.exec(text)?.[1])
    const height = Number(/height="([\d.]+)"/.exec(text)?.[1])
    if (Number.isFinite(width) && width > 0 && Number.isFinite(height) && height > 0) return { width, height }
    throw new Error(`icon-assets: ${file} carries no usable viewBox/width/height`)
  }
  if (file.endsWith('.png') && bytes.length > 24 && bytes.readUInt32BE(12) === 0x49484452) {
    return { width: bytes.readUInt32BE(16), height: bytes.readUInt32BE(20) }
  }
  throw new Error(`icon-assets: ${file} is not a readable PNG (missing IHDR)`)
}

const entries = Object.entries(map).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
if (entries.length === 0) throw new Error('icon-assets: manifest.map is empty')
if (map['native'] === undefined) throw new Error('icon-assets: manifest.map must map the native runtime')

const blocks = []
for (const [runtimeId, file] of entries) {
  if (typeof file !== 'string' || file === '') throw new Error(`icon-assets: manifest entry "${runtimeId}" has no file`)
  const bytes = readFileSync(join(ASSETS, file))
  const mime = MIME[file.slice(file.lastIndexOf('.'))]
  if (mime === undefined) throw new Error(`icon-assets: ${file} has an unsupported extension`)
  const { width, height } = dimensions(file, bytes)
  if (!(width > 0) || !(height > 0)) throw new Error(`icon-assets: ${file} has non-positive dimensions`)
  const tile = tiles[file]
  if (tile !== undefined && typeof tile !== 'string') throw new Error(`icon-assets: tiles["${file}"] must be a color string`)
  blocks.push([
    `  '${runtimeId}': {`,
    `    uri: 'data:${mime};base64,${bytes.toString('base64')}',`,
    `    ratio: ${(width / height).toPrecision(6)},`,
    `    ${tile === undefined ? '' : `tile: '${tile}',`}`,
    `  },`,
  ].filter((line) => line !== '    ').join('\n'))
}

const out = `/**
 * GENERATED by scripts/build-icon-assets.mjs from assets/icons/manifest.json —
 * do not edit; regenerate (npm run build-client runs it). One inlined asset
 * per manifest-mapped runtimeId; \`ratio\` is the intrinsic width/height so the
 * renderer can size non-square marks (the DSH fish), \`tile\` the opaque
 * backing color for marks that would vanish on a dark frame.
 *
 * @module superd-hub/client/icon-assets.gen
 */

/** One embedded runtime mark: data URI, intrinsic ratio, optional tile color. */
export interface RuntimeIconAsset {
  readonly uri: string
  readonly ratio: number
  readonly tile?: string
}

export const RUNTIME_ICON_ASSETS: Readonly<Record<string, RuntimeIconAsset>> = {
${blocks.join('\n')}
}
`
writeFileSync(OUT, out)
console.log(`[icon-assets] wrote ${OUT} (${blocks.length} runtime marks)`)
